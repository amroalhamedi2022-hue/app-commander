package com.appcommander.mobile.data

import java.io.IOException
import java.io.InputStream
import java.io.OutputStream
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

/**
 * Offline SAF export of the installed BASE + ALL split APKs as one ZIP.
 * Uses only JDK ZIP streaming and the existing bounded SHA-256 copier.
 * This is an archive, NOT a user-data backup, signature verifier or installer.
 */
internal object InstalledApkBundleExport {
    const val MAX_TOTAL_BYTES = 2L * 1024 * 1024 * 1024
    const val MAX_APK_COUNT = 64
    private val packagePattern = Regex("[A-Za-z_][A-Za-z0-9_]*(\\.[A-Za-z_][A-Za-z0-9_]*)+")

    data class Source(
        val name: String,
        val expectedBytes: Long,
        val open: () -> InputStream,
    )

    data class EntryDigest(val name: String, val bytes: Long, val sha256: String)
    data class Result(val packageName: String, val totalApkBytes: Long, val entries: List<EntryDigest>)

    /**
     * A successful write only proves that the output stream accepted bytes.
     * Reopen the SAF document after closing it and independently verify every
     * APK digest, ZIP directory and manifest before reporting export success.
     *
     * A caller MUST wrap this in withPartialDocumentCleanup, restricted to the
     * newly created document. Reopening can fail for some SAF providers; fail
     * closed rather than reporting an unverified backup as complete.
     * No APK is installed or extracted during verification.
     */
    @Throws(IOException::class)
    fun writeAndVerify(
        packageName: String,
        sources: List<Source>,
        openForWrite: () -> OutputStream,
        openForRead: () -> InputStream,
    ): Result {
        // write() closes its output, making provider-side commit visible before
        // the independent read. verify() closes its input on every exit path.
        // Validate all caller-controlled metadata BEFORE opening a SAF document;
        // opening a document may create or truncate provider-side content.
        val declaredTotal = validateSources(packageName, sources)
        val written = writeValidated(packageName, sources, openForWrite(), declaredTotal)
        val verified = InstalledApkBundleVerifier.verify(openForRead())
        if (verified.packageName != written.packageName ||
            verified.totalApkBytes != written.totalApkBytes ||
            verified.entries != written.entries
        ) {
            throw IOException("SAF APK bundle changed after export")
        }
        return written
    }

    /**
     * All source names are generated by App Commander, never taken from a
     * filesystem path or untrusted split label. Reject invalid input BEFORE
     * touching the SAF destination. A caller must delete the new document on
     * any failure (InstalledApkExport.withPartialDocumentCleanup).
     */
    /**
     * Validate metadata before opening a provider destination. SAF document
     * creation is an external side effect and must not happen for invalid input.
     */
    @Throws(IOException::class)
    private fun validateSources(packageName: String, sources: List<Source>): Long {
        if (!packagePattern.matches(packageName)) throw IOException("Invalid package name")
        if (sources.isEmpty() || sources.size > MAX_APK_COUNT) {
            throw IOException("Unsupported installed APK count")
        }
        var declaredTotal = 0L
        sources.forEachIndexed { index, source ->
            val expectedName = if (index == 0) "base.apk" else
                "split_${index.toString().padStart(3, '0')}.apk"
            if (source.name != expectedName) throw IOException("Invalid APK archive entry name")
            if (source.expectedBytes !in 1..ApkCacheCopy.MAX_APK_BYTES ||
                source.expectedBytes > MAX_TOTAL_BYTES - declaredTotal
            ) throw IOException("Installed APK bundle exceeds export limits")
            declaredTotal += source.expectedBytes
        }
        return declaredTotal
    }

    @Throws(IOException::class)
    fun write(packageName: String, sources: List<Source>, destination: OutputStream): Result {
        val declaredTotal = validateSources(packageName, sources)
        return writeValidated(packageName, sources, destination, declaredTotal)
    }

    @Throws(IOException::class)
    private fun writeValidated(
        packageName: String,
        sources: List<Source>,
        destination: OutputStream,
        declaredTotal: Long,
    ): Result {
        val digests = ArrayList<EntryDigest>(sources.size)
        ZipOutputStream(destination).use { zip ->
            // APKs are already ZIP-compressed; level zero avoids wasted CPU.
            zip.setLevel(0)
            for (source in sources) {
                zip.putNextEntry(ZipEntry(source.name).apply { time = 0L })
                val copied = source.open().use { input ->
                    ApkCacheCopy.copyWithSha256(input, zip, source.expectedBytes)
                }
                if (copied.sizeBytes != source.expectedBytes) {
                    throw IOException("Installed APK changed or was truncated during export")
                }
                digests.add(EntryDigest(source.name, copied.sizeBytes, copied.sha256))
                zip.closeEntry()
            }
            val manifest = buildString {
                append("{\"format\":\"app-commander-apk-bundle-v1\",")
                append("\"packageName\":\"").append(packageName).append("\",")
                append("\"containsAppData\":false,\"signatureVerified\":false,")
                append("\"entries\":[")
                digests.forEachIndexed { index, entry ->
                    if (index != 0) append(',')
                    append("{\"name\":\"").append(entry.name).append("\",")
                    append("\"size\":").append(entry.bytes).append(',')
                    append("\"sha256\":\"").append(entry.sha256).append("\"}")
                }
                append("]}")
            }
            zip.putNextEntry(ZipEntry("manifest.json").apply { time = 0L })
            zip.write(manifest.toByteArray(Charsets.UTF_8))
            zip.closeEntry()
            zip.finish()
        }
        return Result(packageName, declaredTotal, digests)
    }
}
